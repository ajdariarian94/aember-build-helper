"""
What aember expects of a container (aember's services/containerd and
doc/aember-format.md):

    <name>.aember                    the package: config.json (how to start
                                     it), lxc.container.conf, image.squashfs
    /etc/aember/containers.json      {"name": ..., "dependencies": [...]}

aember-containerd installs the package into /var/lib/aember/<name>/, mounts
the SquashFS (lower) with a tmpfs-backed overlay at
/var/lib/aember/containers/<name>, binds the host's /var/log at /host-logs
and its static BusyBox as /busybox.aember-init (the init wrapper that passes
SIGTERM on), then starts the container with LXC and runs "command" in it.
"""

from __future__ import annotations

from .manifest import Bridge, Manifest

AEMBER_LIB = "/var/lib/aember"


# cgroup2 device rules for null, zero, full, random, urandom, tty, console,
# ptmx and the pts: added whenever a manifest has `device_allow`.
BASE_DEVICE_ALLOW = (
    "c 1:3 rwm",
    "c 1:5 rwm",
    "c 1:7 rwm",
    "c 1:8 rwm",
    "c 1:9 rwm",
    "c 5:0 rwm",
    "c 5:1 rwm",
    "c 5:2 rwm",
    "c 136:* rwm",
)


def package_name(name: str) -> str:
    return f"{name}.aember"


def console_log_path(name: str) -> str:
    """Where the container's console output goes (aember's /var/log)."""
    return f"/var/log/aember-container-{name}.log"


def rootfs_path(name: str) -> str:
    return f"{AEMBER_LIB}/containers/{name}"


# Directories aember and LXC mount over: they must exist in the image.
MOUNT_POINTS = {
    "proc": 0o555,
    "sys": 0o555,
    "dev": 0o755,
    "tmp": 0o1777,
    "run": 0o755,
    "host-logs": 0o755,
}


def lxc_config(m: Manifest) -> str:
    lines = [
        f"# {m.name}: generated by aember-build-helper (aember build)",
        f"lxc.uts.name = {m.name}",
        f"lxc.rootfs.path = dir:{rootfs_path(m.name)}",
        "lxc.mount.auto = proc:mixed sys:mixed",
        "lxc.autodev = 1",
        "lxc.pty.max = 1",
        "lxc.log.level = WARN",
        f"lxc.log.file = /tmp/lxc-{m.name}.log",
    ]
    if m.console_log:
        lines += [
            "# The app's output (the container console), kept on the device",
            f"lxc.console.logfile = {console_log_path(m.name)}",
            "lxc.console.size = 1MB",
            "lxc.console.rotate = 1",
        ]
    lines.append("")
    if m.network == "host":
        lines.append("# Network: aember's own (the host network namespace)")
        lines.append("lxc.net.0.type = none")
    elif m.network == "isolated":
        lines.append("# Network: none, only loopback")
        lines.append("lxc.net.0.type = empty")
    elif isinstance(m.network, Bridge):
        lines += [
            f"# Network: a veth on aember's bridge {m.network.name}",
            "lxc.net.0.type = veth",
            f"lxc.net.0.link = {m.network.name}",
            "lxc.net.0.flags = up",
            f"lxc.net.0.ipv4.address = {m.network.address}",
        ]
        if m.network.gateway:
            lines.append(f"lxc.net.0.ipv4.gateway = {m.network.gateway}")

    if m.env:
        lines.append("")
        lines += [f"lxc.environment = {k}={v}" for k, v in sorted(m.env.items())]
    if m.workdir:
        lines.append(f"lxc.init.cwd = {m.workdir}")
    if m.devices or m.device_allow:
        lines.append("")
        lines.append("# Devices (optional binds: the container starts without them)")
        if m.device_allow:
            # One allow rule turns cgroup2's device filter into an allow-list:
            # without these the init can't even open /dev/null and exits 1.
            lines.append("# The basics every container needs, then the manifest's")
            lines += [f"lxc.cgroup2.devices.allow = {r}" for r in BASE_DEVICE_ALLOW]
        for rule in m.device_allow:
            lines.append(f"lxc.cgroup2.devices.allow = {rule}")
        for dev in m.devices:
            rel = dev.lstrip("/")
            kind = (
                "dir"
                if dev.rstrip("/") in ("/dev/dri", "/dev/input", "/dev/snd")
                else "file"
            )
            lines.append(
                f"lxc.mount.entry = {dev} {rel} none bind,create={kind},optional 0 0"
            )
    if m.lxc:
        lines.append("")
        lines.append("# Extra lines from the manifest")
        lines += m.lxc
    return "\n".join(lines) + "\n"


def config_json(m: Manifest, command: list[str]) -> dict:
    """The package's config.json: how containerd starts the container."""
    return {
        "name": m.name,
        "command": command,
        "init": m.init,
        "stop_timeout": m.stop_timeout,
        "restart_policy": m.restart_policy,
        "max_restart_attempts": m.max_restart_attempts,
        "restart_delay": m.restart_delay,
    }


def containers_entry(m: Manifest) -> dict:
    """The entry for /etc/aember/containers.json: the name, and what must
    run before it."""
    entry: dict = {"name": m.name}
    if m.dependencies:
        entry["dependencies"] = m.dependencies
    return entry
